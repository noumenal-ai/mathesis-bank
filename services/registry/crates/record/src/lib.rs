//! Deterministic static generation of the verified record (SPEC.md §10).
//!
//! The whole tree is a pure function of (immutable registry rows, the pin, the
//! generator version) plus one further, named input class — the profile identity
//! rows behind `u/<login>/`, `profiles*.json` and `_redirects.json`, which is why
//! a rename enqueues a regeneration rather than being left to drift. No clock,
//! no RNG, no map iteration order, no login inside `[data-region="verified"]`,
//! no note and no asset hash reaches a page, so two runs over an unchanged
//! registry produce byte-identical output and `recordgen --check` cannot alarm
//! on an ordinary note edit.

